import { Injectable, Inject, NotFoundException } from '@nestjs/common';
import { randomUUID } from 'crypto';
import {
  ToolResultNoteDraftStatus,
  AuditActorType,
  AuditEventType,
  type ToolResultNoteDraft as ToolResultNoteDraftShape,
  type AuditEvent,
} from '@supportplane/contracts';
import { computeIntegrityHash } from '@supportplane/audit';
import type { Store } from '../store/store.interface.js';
import { InMemoryStore } from '../support-sessions/in-memory.store.js';
import type { CurrentIdentity } from '../auth/auth.types.js';

@Injectable()
export class ToolResultNoteDraftService {
  constructor(@Inject(InMemoryStore) private readonly store: Store) {}

  async createDraftFromResult(
    identity: CurrentIdentity,
    invocationId: string,
    options?: { ticketId?: string; title?: string },
  ): Promise<ToolResultNoteDraftShape> {
    const invocation = await this.store.getToolInvocation(identity.tenantId, invocationId);
    if (!invocation) throw new NotFoundException('Tool invocation not found.');
    if (invocation.status !== 'succeeded') {
      throw new NotFoundException('Tool invocation has not succeeded; cannot create note draft.');
    }

    const existing = await this.store.getToolResultNoteDraftByInvocationId(invocationId);
    if (existing) return existing;

    const body = this.formatResultBody(invocation);
    const now = new Date().toISOString();
    const draft: ToolResultNoteDraftShape = {
      id: randomUUID() as ToolResultNoteDraftShape['id'],
      tenantId: identity.tenantId as ToolResultNoteDraftShape['tenantId'],
      invocationId: invocationId as ToolResultNoteDraftShape['invocationId'],
      ticketId: options?.ticketId,
      title: options?.title ?? `Tool result: ${invocation.toolKey}`,
      body,
      status: ToolResultNoteDraftStatus.enum.draft,
      createdByUserId: identity.userId,
      createdAt: now,
      updatedAt: now,
    };
    await this.store.saveToolResultNoteDraft(draft);

    const event: AuditEvent = {
      id: randomUUID() as AuditEvent['id'],
      tenantId: identity.tenantId as AuditEvent['tenantId'],
      actorId: identity.userId,
      actorType: AuditActorType.enum.user,
      eventType: AuditEventType.enum.tool_note_draft_created,
      action: 'tool_note_draft_created',
      resourceType: 'tool_result_note_draft',
      resourceId: draft.id as AuditEvent['resourceId'],
      metadata: { invocationId, toolKey: invocation.toolKey, ticketId: options?.ticketId },
      createdAt: now,
    };
    event.integrityHash = computeIntegrityHash(event);
    await this.store.saveAuditEvent(event);

    return draft;
  }

  async getDraft(tenantId: string, id: string): Promise<ToolResultNoteDraftShape | undefined> {
    return this.store.getToolResultNoteDraft(tenantId, id);
  }

  async listDrafts(tenantId: string): Promise<ToolResultNoteDraftShape[]> {
    return this.store.listToolResultNoteDrafts(tenantId);
  }

  private formatResultBody(invocation: { toolKey: string; normalizedResult: Record<string, unknown>; completedAt?: string }): string {
    return [
      `## Tool Result: ${invocation.toolKey}`,
      '',
      `- **Status:** Succeeded`,
      `- **Completed:** ${invocation.completedAt ?? 'unknown'}`,
      '',
      '### Result Payload',
      '',
      '```json',
      JSON.stringify(invocation.normalizedResult, null, 2),
      '```',
      '',
      '> **Draft only — not sent to external ticketing system.**',
      '> Generated by SupportPlane tool execution gateway.',
    ].join('\n');
  }
}
